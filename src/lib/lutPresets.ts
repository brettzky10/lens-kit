export interface LutPreset {
  id: string;
  name: string;
  // A CSS gradient used purely for the picker grid's preview swatch — a
  // quick visual sense of the look's color mood before an image is even
  // connected.
  previewGradient: string;
  // Per-channel lift/gamma/gain, the standard color-grading model:
  //   out = pow(in, 1/gamma) * gain + lift
  // Applied per R/G/B channel, each in [0,1] space.
  lift: [number, number, number];
  gamma: [number, number, number];
  gain: [number, number, number];
  // Extra: saturation multiplier (1 = unchanged, 0 = grayscale) and
  // contrast multiplier (1 = unchanged), applied after lift/gamma/gain.
  saturation: number;
  contrast: number;
}

