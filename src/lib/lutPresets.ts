/**
 * Applies a preset's lift/gamma/gain/saturation/contrast transform in place
 * to a canvas ImageData's pixel buffer.
 */
export function applyLutToPixels(pixels: Uint8ClampedArray, preset: LutPreset) {
  const { lift, gamma, gain, saturation, contrast } = preset;

  for (let i = 0; i < pixels.length; i += 4) {
    let r = pixels[i] / 255;
    let g = pixels[i + 1] / 255;
    let b = pixels[i + 2] / 255;

    // Lift / gamma / gain per channel
    r = Math.pow(Math.max(r, 0), 1 / gamma[0]) * gain[0] + lift[0];
    g = Math.pow(Math.max(g, 0), 1 / gamma[1]) * gain[1] + lift[1];
    b = Math.pow(Math.max(b, 0), 1 / gamma[2]) * gain[2] + lift[2];

    // Saturation (mix toward luminance)
    if (saturation !== 1) {
      const lum = 0.2126 * r + 0.7152 * g + 0.0722 * b;
      r = lum + (r - lum) * saturation;
      g = lum + (g - lum) * saturation;
      b = lum + (b - lum) * saturation;
    }

    // Contrast (pivot around 0.5)
    if (contrast !== 1) {
      r = (r - 0.5) * contrast + 0.5;
      g = (g - 0.5) * contrast + 0.5;
      b = (b - 0.5) * contrast + 0.5;
    }

    pixels[i] = Math.max(0, Math.min(255, r * 255));
    pixels[i + 1] = Math.max(0, Math.min(255, g * 255));
    pixels[i + 2] = Math.max(0, Math.min(255, b * 255));
  }
}

/**
 * Loads an image (by URL/data URL), applies the given preset via canvas,
 * and resolves with a JPEG data URL of the result. Runs entirely
 * client-side — no API calls, no cost, near-instant.
 *
 * Note: loading a *cross-origin* image URL that doesn't send permissive
 * CORS headers will make the canvas "tainted" and getImageData() will
 * throw a security error — this mainly affects images hosted on services
 * that don't set Access-Control-Allow-Origin. Images generated by this
 * app's own Replicate calls, and locally-dropped Reference node images,
 * both work fine.
 */
export function applyLutToImage(imageUrl: string, preset: LutPreset): Promise<string> {
  return new Promise((resolve, reject) => {
    const img = new window.Image();
    img.crossOrigin = "anonymous";
    img.onload = () => {
      try {
        const canvas = document.createElement("canvas");
        canvas.width = img.naturalWidth;
        canvas.height = img.naturalHeight;
        const ctx = canvas.getContext("2d");
        if (!ctx) {
          reject(new Error("Canvas not supported."));
          return;
        }
        ctx.drawImage(img, 0, 0);
        const imageData = ctx.getImageData(0, 0, canvas.width, canvas.height);
        applyLutToPixels(imageData.data, preset);
        ctx.putImageData(imageData, 0, 0);
        resolve(canvas.toDataURL("image/jpeg", 0.9));
      } catch (err) {
        reject(
          new Error(
            "Could not read pixel data from this image — it's likely hosted somewhere that blocks cross-origin canvas access (CORS)."
          )
        );
      }
    };
    img.onerror = () => reject(new Error("Could not load the image."));
    img.src = imageUrl;
  });
}
